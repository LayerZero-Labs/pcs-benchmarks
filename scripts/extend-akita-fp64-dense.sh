#!/usr/bin/env bash
# Add nv=21,23,25,27 to a cloned Akita fp64-dense catalog using that
# revision's planner. The upstream pin ships nv ∈ {14,16,20,26,28,29,30}.
# Hash-eval needs 21/23/25/27 (and already has 29) for payloads 2^27..2^35.
#
# Usage: extend-akita-fp64-dense.sh <akita-checkout>
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="$(cd "${1:?usage: extend-akita-fp64-dense.sh <akita-checkout>}" && pwd)"

if [[ ! -d "$DEST/.git" ]]; then
  echo "error: $DEST is not a git checkout" >&2
  exit 2
fi

python3 - "$DEST" <<'PY'
from pathlib import Path
import re
import sys

root = Path(sys.argv[1])
path = root / "crates/akita-planner/src/generated_families.rs"
text = path.read_text()
notice = "// Modified for PCS Benchmarks to add nv=21,23,25,27 schedule rows.\n"
old = """const FP64_DENSE_KEYS: &[PolynomialGroupLayout] = &[
    PolynomialGroupLayout::singleton(14),
    // Produces the frozen profile for the precommit half of
    // `fp64_dense_grouped_requests`, which needs 16: at 14 or 15 the prover and
    // the planned schedule disagree on the fold-level-1 witness length.
    PolynomialGroupLayout::singleton(16),
    PolynomialGroupLayout::singleton(20),
    PolynomialGroupLayout::singleton(26),
    PolynomialGroupLayout::singleton(28),
    PolynomialGroupLayout::singleton(29),
    PolynomialGroupLayout::singleton(30),
];"""
new = """const FP64_DENSE_KEYS: &[PolynomialGroupLayout] = &[
    PolynomialGroupLayout::singleton(14),
    // Produces the frozen profile for the precommit half of
    // `fp64_dense_grouped_requests`, which needs 16: at 14 or 15 the prover and
    // the planned schedule disagree on the fold-level-1 witness length.
    PolynomialGroupLayout::singleton(16),
    PolynomialGroupLayout::singleton(20),
    PolynomialGroupLayout::singleton(21),
    PolynomialGroupLayout::singleton(23),
    PolynomialGroupLayout::singleton(25),
    PolynomialGroupLayout::singleton(26),
    PolynomialGroupLayout::singleton(27),
    PolynomialGroupLayout::singleton(28),
    PolynomialGroupLayout::singleton(29),
    PolynomialGroupLayout::singleton(30),
];"""
changed = False
if not text.startswith(notice):
    text = notice + text
    changed = True
block = re.search(r"const FP64_DENSE_KEYS:.*?];", text, re.S)
if block and "singleton(21)" in block.group(0) and "singleton(23)" in block.group(0):
    print(f"{path}: nv=21/23/25/27 already listed")
elif old not in text:
    sys.exit(f"{path}: expected FP64_DENSE_KEYS block not found")
else:
    text = text.replace(old, new, 1)
    changed = True
    print(f"{path}: added nv=21,23,25,27")
if changed:
    path.write_text(text)
PY

cd "$DEST"
"$DEST/scripts/generate-schedule-tables.sh" --row-progress fp64_dense

python3 - "$DEST" "$ROOT" <<'PY'
from pathlib import Path
import shutil
import sys

dest = Path(sys.argv[1])
root = Path(sys.argv[2])
generated = dest / "crates/akita-schedules/src/generated/fp64_dense.rs"
overlay = root / "vendor/akita-catalogs/fp64_dense-main.rs"
text = generated.read_text()
generated_hdr = "// Generated by "
notice = "// Modified for PCS Benchmarks to add the nv=21,23,25,27 schedule rows.\n"
if notice not in text:
    if not text.startswith(generated_hdr):
        sys.exit(f"{generated}: generated header not found")
    first_line, rest = text.split("\n", 1)
    generated.write_text(f"{first_line}\n{notice}{rest}")
    text = generated.read_text()
overlay.parent.mkdir(parents=True, exist_ok=True)
shutil.copyfile(generated, overlay)
print(f"copied {generated} -> {overlay}")
PY
