#!/usr/bin/env bash
# Generate the fp<width>-dense-recursive (setup-offload) catalog for a pinned Akita checkout.
#
# Usage: extend-akita-dense-offload.sh <akita-checkout> [fp32|fp64|fp128]
# Requires the pinned Akita revision used by fetch-vendors.sh.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="$(cd "${1:?usage: extend-akita-dense-offload.sh <akita-checkout> [field]}" && pwd)"
FIELD="${2:-fp32}"

case "$FIELD" in
  fp32|fp64|fp128) ;;
  *) echo "error: field must be fp32, fp64, or fp128 (got $FIELD)" >&2; exit 2 ;;
esac

if [[ ! -d "$DEST/.git" ]]; then
  echo "error: $DEST is not a git checkout" >&2
  exit 2
fi

FAMILY="${FIELD}_dense_recursive"

python3 "$ROOT/scripts/patch-akita-dense-offload.py" "$DEST" --field "$FIELD"

cd "$DEST"
"$DEST/scripts/generate-schedule-tables.sh" --row-progress "$FAMILY"

python3 - "$DEST" "$ROOT" "$FAMILY" <<'PY'
from pathlib import Path
import shutil
import sys

dest, root, family = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
generated = dest / f"crates/akita-schedules/src/generated/{family}.rs"
overlay = root / f"vendor/akita-catalogs/{family}-main.rs"
text = generated.read_text()
generated_hdr = "// Generated by "
notice = f"// Modified for PCS Benchmarks to add the {family} setup-offload schedule family.\n"
if notice not in text:
    if not text.startswith(generated_hdr):
        sys.exit(f"{generated}: generated header not found")
    first_line, rest = text.split("\n", 1)
    generated.write_text(f"{first_line}\n{notice}{rest}")
    text = generated.read_text()
overlay.parent.mkdir(parents=True, exist_ok=True)
shutil.copyfile(generated, overlay)
print(f"copied {generated} -> {overlay}")
if "setup_prefix: Some(" not in text:
    sys.exit(
        f"{generated}: generated catalog has no setup-prefix edges; "
        "the offload variant would not offload setup"
    )
rows = text.count("setup_prefix: Some(")
print(f"catalog contains {rows} setup-prefix (offload) edge(s)")
PY
