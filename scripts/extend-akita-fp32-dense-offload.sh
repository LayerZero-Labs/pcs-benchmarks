#!/usr/bin/env bash
# Generate the fp32-dense-recursive (setup-offload) catalog for lattice-eval.
#
# Usage: extend-akita-fp32-dense-offload.sh <akita-checkout>
# Requires the pinned Akita revision used by fetch-vendors.sh.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="$(cd "${1:?usage: extend-akita-fp32-dense-offload.sh <akita-checkout>}" && pwd)"

if [[ ! -d "$DEST/.git" ]]; then
  echo "error: $DEST is not a git checkout" >&2
  exit 2
fi

python3 "$ROOT/scripts/patch-akita-fp32-dense-offload.py" "$DEST"

cd "$DEST"
"$DEST/scripts/generate-schedule-tables.sh" --row-progress fp32_dense_recursive

python3 - "$DEST" "$ROOT" <<'PY'
from pathlib import Path
import shutil
import sys

dest = Path(sys.argv[1])
root = Path(sys.argv[2])
generated = dest / "crates/akita-schedules/src/generated/fp32_dense_recursive.rs"
overlay = root / "vendor/akita-catalogs/fp32_dense_recursive-main.rs"
text = generated.read_text()
generated_hdr = "// Generated by "
notice = "// Modified for PCS Benchmarks to add the nv=20,22,24,26,28,30 setup-offload schedule family.\n"
if notice not in text:
    if not text.startswith(generated_hdr):
        sys.exit(f"{generated}: generated header not found")
    first_line, rest = text.split("\n", 1)
    generated.write_text(f"{first_line}\n{notice}{rest}")
    text = generated.read_text()
overlay.parent.mkdir(parents=True, exist_ok=True)
shutil.copyfile(generated, overlay)
print(f"copied {generated} -> {overlay}")
if "setup_prefix: Some(" not in text:
    sys.exit(
        f"{generated}: generated catalog has no setup-prefix edges; "
        "the offload variant would not offload setup"
    )
print("catalog contains at least one setup-prefix (offload) edge")
PY
