#!/usr/bin/env bash
# Add nv=20 and nv=22 to a cloned Akita fp128-dense catalog using that
# revision's planner. The upstream pin ships nv ∈ {14,15×2,16,16×2,17×4,24,26,28,30,32}.
# Hash-eval needs 20 and 22 for payloads 2^27 and 2^29; 24/26/28 already exist.
#
# Usage: extend-akita-fp128-dense.sh <akita-checkout>
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
DEST="$(cd "${1:?usage: extend-akita-fp128-dense.sh <akita-checkout>}" && pwd)"

if [[ ! -d "$DEST/.git" ]]; then
  echo "error: $DEST is not a git checkout" >&2
  exit 2
fi

python3 - "$DEST" <<'PY'
from pathlib import Path
import re
import sys

root = Path(sys.argv[1])
path = root / "crates/akita-planner/src/generated_families.rs"
text = path.read_text()
notice = "// Modified for PCS Benchmarks to add nv=20 and nv=22 schedule rows.\n"
old = """const FP128_DENSE_KEYS: &[PolynomialGroupLayout] = &[
    PolynomialGroupLayout::singleton(14),
    PolynomialGroupLayout::new(15, 2),
    PolynomialGroupLayout::singleton(16),
    PolynomialGroupLayout::new(16, 2),
    PolynomialGroupLayout::new(17, 4),
    PolynomialGroupLayout::singleton(24),
    PolynomialGroupLayout::singleton(26),
    PolynomialGroupLayout::singleton(28),
    PolynomialGroupLayout::singleton(30),
    PolynomialGroupLayout::singleton(32),
];"""
new = """const FP128_DENSE_KEYS: &[PolynomialGroupLayout] = &[
    PolynomialGroupLayout::singleton(14),
    PolynomialGroupLayout::new(15, 2),
    PolynomialGroupLayout::singleton(16),
    PolynomialGroupLayout::new(16, 2),
    PolynomialGroupLayout::new(17, 4),
    PolynomialGroupLayout::singleton(20),
    PolynomialGroupLayout::singleton(22),
    PolynomialGroupLayout::singleton(24),
    PolynomialGroupLayout::singleton(26),
    PolynomialGroupLayout::singleton(28),
    PolynomialGroupLayout::singleton(30),
    PolynomialGroupLayout::singleton(32),
];"""
changed = False
if not text.startswith(notice):
    text = notice + text
    changed = True
block = re.search(r"const FP128_DENSE_KEYS:.*?];", text, re.S)
if block and "singleton(20)" in block.group(0) and "singleton(22)" in block.group(0):
    print(f"{path}: nv=20/22 already listed")
elif old not in text:
    sys.exit(f"{path}: expected FP128_DENSE_KEYS block not found")
else:
    text = text.replace(old, new, 1)
    changed = True
    print(f"{path}: added nv=20 and nv=22")
if changed:
    path.write_text(text)
PY

cd "$DEST"
"$DEST/scripts/generate-schedule-tables.sh" --row-progress fp128_dense

python3 - "$DEST" "$ROOT" <<'PY'
from pathlib import Path
import shutil
import sys

dest = Path(sys.argv[1])
root = Path(sys.argv[2])
generated = dest / "crates/akita-schedules/src/generated/fp128_dense.rs"
overlay = root / "vendor/akita-catalogs/fp128_dense-main.rs"
text = generated.read_text()
generated_hdr = "// Generated by "
notice = "// Modified for PCS Benchmarks to add the nv=20 and nv=22 schedule rows.\n"
if notice not in text:
    if not text.startswith(generated_hdr):
        sys.exit(f"{generated}: generated header not found")
    first_line, rest = text.split("\n", 1)
    generated.write_text(f"{first_line}\n{notice}{rest}")
    text = generated.read_text()
overlay.parent.mkdir(parents=True, exist_ok=True)
shutil.copyfile(generated, overlay)
print(f"copied {generated} -> {overlay}")
PY
